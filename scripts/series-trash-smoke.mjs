// Run against an isolated local dev server whose AID_COMPANION_DATA_DIR is a temporary directory.
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { parseOutline, parseEpisodes } from '../lib/series/domain.ts';
import { outlineFixture, episodeFixtures } from '../tests/fixtures/series.mjs';
const base = process.argv[2], dir = process.env.AID_COMPANION_DATA_DIR;
assert.ok(base && ['localhost', '127.0.0.1'].includes(new URL(base).hostname));
assert.ok(dir && path.resolve(dir).startsWith(path.resolve(os.tmpdir()) + path.sep), 'Use an isolated OS temp directory');
async function request(body) {
  const r = await fetch(`${base}/api/companion/series`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const data = await r.json(); if (!r.ok) throw new Error(data.error); return data;
}
const snapshot = () => fetch(`${base}/api/companion/series`).then(r => r.json());
assert.equal((await snapshot()).projects.length, 0, 'Use a fresh empty server');
const settings = { apiKey: 'fixture-never-send', fishAudioKey: 'fixture-never-send' };
const workerId = `trash-qa-${crypto.randomUUID()}`;
await request({ action: 'claim', workerId, mode: 'companion' });
const { project } = await request({ action: 'create', project: { name: '删除与恢复 · 验证样例', brief: '隔离删除验证', episodeCount: 3 } });
const seriesId = project.id;
await request({ action: 'enqueue', seriesId, kind: 'develop', settings });
const { claim } = await request({ action: 'claim', workerId, mode: 'companion' });
await assert.rejects(request({ action: 'trash', seriesId, revision: project.revision, confirmName: project.name }), /暂停/);
Object.assign(claim.project, parseOutline(outlineFixture(), claim.project));
claim.project.episodes = parseEpisodes(episodeFixtures(), claim.project, 1, 3);
const film = Buffer.from('isolated retained media bytes');
claim.project.episodes[0].deliveries = [{ id: 'retained-film', fileName: 'keep.mp4', bytes: film.length, episodeVersion: 1 }];
const folder = path.join(dir, 'series', seriesId);
await mkdir(folder, { recursive: true });
await writeFile(path.join(folder, 'retained-film.mp4'), film);
await request({ action: 'checkpoint', jobId: claim.job.id, lease: claim.job.lease, project: claim.project });
await request({ action: 'finish', jobId: claim.job.id, lease: claim.job.lease, error: 'fixture failure preserved' });
await request({ action: 'enqueue', seriesId, kind: 'prepare', settings });
const before = (await snapshot()).projects[0];
await assert.rejects(request({ action: 'trash', seriesId, revision: 0, confirmName: before.name }), /已有更新/);
await assert.rejects(request({ action: 'trash', seriesId, revision: before.revision, confirmName: 'wrong-project' }), /确认/);
await request({ action: 'trash', seriesId, revision: before.revision, confirmName: before.name });
const trashed = await snapshot();
assert.equal(trashed.projects.length, 0); assert.equal(trashed.jobs.length, 0);
assert.equal(trashed.trashedProjects[0].deliveryCount, 1);
assert.equal((await request({ action: 'claim', workerId, mode: 'companion' })).claim, null);
for (const action of ['resume', 'edit', 'cast-character', 'enqueue'])
  await assert.rejects(request({ action, seriesId, kind: 'develop', settings }), /回收站/);
await assert.rejects(request({ action: 'retry', jobId: claim.job.id }), /回收站/);
await assert.rejects(request({ action: 'checkpoint', jobId: claim.job.id, lease: claim.job.lease, project: before }), /租约/);
const url = `${base}/api/companion/series/delivery?seriesId=${seriesId}&id=retained-film`;
assert.equal((await fetch(url)).status, 404);
assert.deepEqual(await readFile(path.join(folder, 'retained-film.mp4')), film);
await request({ action: 'restore', seriesId, revision: trashed.trashedProjects[0].revision });
const restored = await snapshot(), p = restored.projects[0];
assert.equal(p.paused, true); assert.equal(restored.trashedProjects.length, 0);
assert.deepEqual(p.episodes, before.episodes); assert.deepEqual(p.characters, before.characters);
assert.equal(restored.jobs.find(j => j.id === claim.job.id).error, 'fixture failure preserved');
assert.equal(restored.jobs.find(j => j.kind === 'prepare').status, 'paused');
assert.equal((await request({ action: 'claim', workerId, mode: 'companion' })).claim, null);
const delivered = await fetch(url); assert.equal(delivered.status, 200);
assert.deepEqual(Buffer.from(await delivered.arrayBuffer()), film);
console.log(JSON.stringify({ ok: true, seriesId, checks: ['running guarded', 'revision and confirmation guarded', 'trash hidden from old clients', 'queue disabled', 'retry and stale write blocked', 'media retained', 'restore stays paused', 'download restored'] }));
